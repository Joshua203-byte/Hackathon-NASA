import type { CellIndicator, Lang } from '../types';
export function Narrative({ data, lang }: { data: CellIndicator; lang: Lang }) {
  if (!data.narrative) return null;
  return (
    <p className="narrative">{data.narrative[lang]} <small>({lang === 'es' ? 'generado por' : 'generated by'}: {data.narrative.generated_by})</small></p>
  );
}
