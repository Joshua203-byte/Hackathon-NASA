import { fmtNum, fmtP, fmtSlope } from './format';
import { indexFootprint, resolveWindow, type FpWindow } from './footprint';
import { VERDICT_UI, reasonText, verdictNotices } from './verdict';
import type { CellDetail, CellIndicator, GridCell, IndicatorKey, Lang, Meta, Win } from './types';

export interface PassportInput {
  cell: CellDetail;
  gridRow: GridCell | null;
  meta: Meta;
  ind: IndicatorKey;
  win: Win | null;
  lang: Lang;
  deepLink: string;
  /** Inyectable para pruebas. */
  now?: Date;
}

/** Traza completa: cada cifra se copia del JSON del pipeline sin redondear ni recalcular. */
export function buildPassport(i: PassportInput) {
  const d = i.cell.indicators[i.ind];
  if (!d) return null;
  const g = i.gridRow?.ind[i.ind] ?? null;
  const total = i.meta.period[1] - i.meta.period[0] + 1;
  const valid = g?.valid_years ?? d.series.filter((p) => typeof p.value === 'number').length;
  const sel = resolveWindow(indexFootprint(d.footprint, d.window_results), i.win, i.meta.period);
  return {
    schema: 'altaris.passport/1',
    data_kind: i.meta.data_kind ?? (i.meta.pipeline_commit === 'MOCK' ? 'mock' : 'unspecified'),
    secondary_variables: i.cell.secondary_variables ?? [],
    exported_at: (i.now ?? new Date()).toISOString(),
    deep_link: i.deepLink,
    provenance: {
      dataset: i.meta.dataset,
      dataset_doi: i.meta.dataset_doi,
      period: i.meta.period,
      pipeline_commit: i.meta.pipeline_commit,
      generated_at: i.meta.generated_at,
      aux_data: i.meta.aux_data,
      thresholds: i.meta.thresholds,
    },
    cell: {
      id: i.cell.id,
      name: i.cell.name,
      lat: i.gridRow?.lat ?? null,
      lon: i.gridRow?.lon ?? null,
      country: i.gridRow?.country ?? null,
    },
    indicator: i.ind,
    units: d.units,
    completeness: { valid_years: valid, total_years: total },
    verdict: d.verdict,
    verdict_reasons: d.verdict_reasons,
    notices: verdictNotices(i.cell, i.ind, d, i.lang).map((n) => n.text),
    statistics: d.statistics,
    stability: {
      sign_agreement: g?.sign_agreement ?? null,
      sig_fraction: g?.sig_fraction ?? null,
      windows_in_footprint: d.footprint.length,
    },
    selected_window: sel.isBase ? null : windowRecord(sel.window),
    enso_test: d.enso_test,
    break_2014: d.break_2014,
    calibration: i.meta.calibration,
    narrative: d.narrative,
    limitations: d.limitations,
    series: d.series,
    footprint: d.footprint,
  };
}
export type Passport = NonNullable<ReturnType<typeof buildPassport>>;

