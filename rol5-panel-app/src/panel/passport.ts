export function passportToMarkdown(p: Passport, lang: Lang): string {
  const t = L[lang];
  const s = p.statistics;
  const ui = VERDICT_UI[p.verdict];
  const yn = (b: boolean | null | undefined) => (b === null || b === undefined ? t.na : b ? t.yes : t.no);
  const pct = (x: number | null | undefined) => (typeof x === 'number' ? `${fmtNum(x * 100, 1)} %` : t.na);
  const out: string[] = [
    `# ${t.title}`,
    '',
    `> ${p.data_kind === "mock" ? (lang === "es" ? "DATOS SIMULADOS: no usar para decisiones." : "SIMULATED DATA: do not use for decisions.") : p.provenance.dataset}`,
    `- **${t.cell}:** ${p.cell.id}${p.cell.name ? ` (${p.cell.name})` : ''}${p.cell.lat !== null ? ` · ${p.cell.lat}, ${p.cell.lon} · ${p.cell.country}` : ''}`,
    `- **${t.ind}:** ${p.indicator} (${p.units})`,
    `- **${t.verdict}:** ${ui.label[lang]}${ui.caveat ? ` — **${ui.caveat[lang]}**` : ''} (\`${p.verdict}\`)`,
    `- ${p.completeness.valid_years}/${p.completeness.total_years} ${t.valid}`,
    '',
  ];
  if (p.verdict_reasons.length) {
    out.push(`## ${t.reasons}`, '', ...p.verdict_reasons.map((r) => `- ${reasonText(r, lang)} (\`${r}\`)`), '');
  }
  if (p.notices.length) out.push(...p.notices.map((n) => `> ${n}`), '');
  out.push(
    `## ${t.trend}`,
    '',
    `- ${t.slope}: ${fmtSlope(s?.slope_per_decade, lang)}`,
    `- ${t.ci}: [${fmtNum(s?.ci_95?.[0])}, ${fmtNum(s?.ci_95?.[1])}]`,
    `- ${t.p}: ${fmtP(s?.p_value)} · ${t.pfdr}: ${fmtP(s?.adjusted_p_fdr)}`,
    `- ${t.method}: ${s ? `${s.method} (${s.mk_variant})` : t.na}`,
    '',
    `## ${t.stab}`,
    '',
    `- ${t.sign}: ${fmtNum(p.stability.sign_agreement, 2)} · ${t.sig}: ${fmtNum(p.stability.sig_fraction, 2)}`,
    '',
  );
  if (p.selected_window) {
    const w = p.selected_window;
    out.push(`## ${t.win}: ${w.start}–${w.end}`, '', `- ${t.slope}: ${fmtSlope(w.slope_per_decade, lang)} · ${t.punc}: ${fmtP(w.p_uncorrected)}`, '');
  }
  if (p.selected_window) {
    const w = p.selected_window;
    out.push(`- ${t.ci}: [${fmtNum(w.ci_95[0])}, ${fmtNum(w.ci_95[1])}]`, `- ${t.verdict}: ${w.verdict ? VERDICT_UI[w.verdict].label[lang] : t.na}`, ...w.verdict_reasons.map(r => `- ${reasonText(r, lang)}`), '');
  }
  for (const v of p.secondary_variables) out.push(`## ${v.label[lang]}`, '', `${v.source} · DOI: ${v.doi} · ${v.period.join('–')}`, `${t.slope}: ${fmtNum(v.data.statistics?.slope_per_decade)} ${v.data.units}/dec`, '');
  const e = p.enso_test;
  out.push(
    `## ${t.enso}`,
    '',
    e
      ? `- ${t.noStrong}: ${fmtSlope(e.slope_without_strong_enso, lang)} (p ${fmtP(e.p_without_strong_enso)})\n- ${t.oni}: ${fmtSlope(e.slope_oni_removed, lang)} (p ${fmtP(e.p_oni_removed)})\n- ${t.survives}: ${yn(e.survives)}`
      : `- ${t.na}`,
    '',
    `## ${t.brk}`,
    '',
    p.break_2014
      ? `- ${t.year}: ${p.break_2014.pettitt_year ?? t.na} · p ${fmtP(p.break_2014.p)} · ${t.flag}: ${yn(p.break_2014.flag)}`
      : `- ${t.na}`,
    '',
    `## ${t.calib}`,
    '',
    p.calibration
      ? `- ${t.fp}: consistente ${pct(p.calibration.false_positive_rate.consistente)}, limitada ${pct(p.calibration.false_positive_rate.limitada)} (n = ${p.calibration.n_sim})\n- ${t.power} (${p.calibration.power.injected_trend_pct_per_decade} %/dec): consistente ${pct(p.calibration.power.detected_consistente)}, limitada+ ${pct(p.calibration.power.detected_limitada_o_mas)}`
      : `- ${t.na}`,
    '',
  );
  if (p.narrative) out.push(`## ${t.narr}`, '', p.narrative[lang], '', `_${t.by}: ${p.narrative.generated_by}_`, '');
  if (p.limitations.length) out.push(`## ${t.lim}`, '', ...p.limitations.map((x) => `- ${x}`), '');
  out.push(
    `## ${t.prov}`,
    '',
    `- ${p.provenance.dataset} · DOI: ${p.provenance.dataset_doi}`,
    `- ${p.provenance.period[0]}–${p.provenance.period[1]} · pipeline \`${p.provenance.pipeline_commit}\` · ${p.provenance.generated_at}`,
    `- Aux: ${p.provenance.aux_data.join('; ')}`,
    `- ${t.link}: ${p.deep_link}`,
    '',
  );
  return out.join('\n');
}

/** Descarga local: sin backend, funciona en incógnito. */
export function downloadText(filename: string, text: string, mime: string) {
  const url = URL.createObjectURL(new Blob([text], { type: `${mime};charset=utf-8` }));
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  a.remove();
  setTimeout(() => URL.revokeObjectURL(url), 0);
}

/** navigator.clipboard exige HTTPS o localhost; si falla, la UI muestra el enlace en un campo seleccionable. */
export async function copyLink(url: string): Promise<boolean> {
  try {
    await navigator.clipboard.writeText(url);
    return true;
  } catch {
    return false;
  }
}
